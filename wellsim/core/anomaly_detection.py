"""Rig Telemetry Anomaly Detector & Drilling Early-Warning Engine.

Real-time statistical and physical anomaly detection shadowing live rig data:
1. Drilling Break Detector (Early kick warning before volume influx)
2. Bit Nozzle Plugging vs. Drillstring Washout Detector
3. Differential Sticking vs. Mechanical Cuttings Pack-Off Classifier
"""

from __future__ import annotations

import math
from collections import deque
from dataclasses import dataclass, field
from enum import Enum
from typing import Deque, List, Optional

__all__ = [
    "DrillingAnomalyType",
    "AnomalyAlert",
    "RigTelemetrySnapshot",
    "RigAnomalyDetector",
]


class DrillingAnomalyType(str, Enum):
    DRILLING_BREAK = "DRILLING_BREAK"
    NOZZLE_PLUGGING = "NOZZLE_PLUGGING"
    STRING_WASHOUT = "STRING_WASHOUT"
    MECHANICAL_PACKOFF = "MECHANICAL_PACKOFF"
    DIFFERENTIAL_STICKING = "DIFFERENTIAL_STICKING"
    KICK_INFLUX = "KICK_INFLUX"


@dataclass(frozen=True)
class AnomalyAlert:
    """An alert generated by the anomaly detector.

    Attributes:
        timestamp_s: Simulation or rig time (seconds).
        anomaly_type: Type of anomaly detected.
        severity: 'WARNING' or 'CRITICAL'.
        message: Diagnostic description and physical signature.
        recommended_action: Standard IADC / IWCF operational procedure to execute.
    """

    timestamp_s: float
    anomaly_type: DrillingAnomalyType
    severity: str
    message: str
    recommended_action: str


@dataclass
class RigTelemetrySnapshot:
    """Single time-step snapshot of live rig sensor telemetry."""

    time_s: float
    rop_ft_hr: float
    spp_psi: float
    pump_spm: float
    torque_ft_lbf: float
    hookload_klbf: float
    pit_gain_bbl: float
    flow_out_pct: float
    is_on_bottom: bool = True


class RigAnomalyDetector:
    """Real-time statistical and hydraulic trend classifier for rig telemetry."""

    def __init__(self, window_size: int = 15) -> None:
        self.window_size = window_size
        self.rop_history: Deque[float] = deque(maxlen=window_size)
        self.spp_history: Deque[float] = deque(maxlen=window_size)
        self.torque_history: Deque[float] = deque(maxlen=window_size)
        self.baseline_impedance: Optional[float] = None  # SPP / SPM^2

    def process_snapshot(self, snap: RigTelemetrySnapshot) -> List[AnomalyAlert]:
        """Process incoming sensor snapshot and evaluate diagnostic rules."""
        alerts: List[AnomalyAlert] = []

        # 1. DRILLING BREAK DETECTION (Only while drilling on bottom)
        if snap.is_on_bottom and snap.rop_ft_hr > 0:
            if len(self.rop_history) >= 5:
                avg_rop = sum(self.rop_history) / len(self.rop_history)
                # If current ROP exceeds 2.2x recent baseline ROP
                if snap.rop_ft_hr >= 2.2 * avg_rop and snap.rop_ft_hr >= 40.0:
                    alerts.append(
                        AnomalyAlert(
                            timestamp_s=snap.time_s,
                            anomaly_type=DrillingAnomalyType.DRILLING_BREAK,
                            severity="WARNING",
                            message=(
                                f"DRILLING BREAK DETECTED: ROP surged from {avg_rop:.1f} ft/hr "
                                f"to {snap.rop_ft_hr:.1f} ft/hr (+{(snap.rop_ft_hr/max(1.0, avg_rop)-1)*100:.0f}%). "
                                f"Bit may have penetrated porous, overpressured reservoir sand."
                            ),
                            recommended_action=(
                                "Stop rotary, pick up off bottom, space out tool joint above rotary table, "
                                "shut down mud pumps, and conduct mandatory flow check."
                            ),
                        )
                    )
            self.rop_history.append(snap.rop_ft_hr)

        # 2. HYDRAULIC IMPEDANCE: NOZZLE PLUGGING vs. WASHOUT (Requires steady pumps)
        if snap.pump_spm >= 40.0 and snap.spp_psi >= 500.0:
            current_imp = snap.spp_psi / (snap.pump_spm**2)
            if self.baseline_impedance is None:
                self.baseline_impedance = current_imp
            else:
                imp_ratio = current_imp / self.baseline_impedance
                # Nozzle plugging: sudden impedance jump >= +18%
                if imp_ratio >= 1.18:
                    alerts.append(
                        AnomalyAlert(
                            timestamp_s=snap.time_s,
                            anomaly_type=DrillingAnomalyType.NOZZLE_PLUGGING,
                            severity="WARNING",
                            message=(
                                f"BIT NOZZLE PLUGGING: SPP increased by "
                                f"+{snap.spp_psi - (self.baseline_impedance * (snap.pump_spm**2)):.0f} psi "
                                f"at steady SPM ({snap.pump_spm:.0f} spm). One or more nozzles obstructed."
                            ),
                            recommended_action=(
                                "Do not increase pump pressure beyond surface equipment limits. "
                                "Work pipe and surge mud pumps; if blockage persists, POOH to inspect bit."
                            ),
                        )
                    )
                # Washout: steady impedance drop <= -15%
                elif imp_ratio <= 0.85:
                    alerts.append(
                        AnomalyAlert(
                            timestamp_s=snap.time_s,
                            anomaly_type=DrillingAnomalyType.STRING_WASHOUT,
                            severity="CRITICAL",
                            message=(
                                f"DRILLSTRING / BIT WASHOUT DETECTED: SPP dropped by "
                                f"-{(self.baseline_impedance * (snap.pump_spm**2)) - snap.spp_psi:.0f} psi "
                                f"at steady SPM ({snap.pump_spm:.0f} spm). High risk of string twist-off!"
                            ),
                            recommended_action=(
                                "IMMEDIATELY stop drilling and pull out of hole (POOH). "
                                "Inspect drillstring tool joints for washout cracks to avoid leaving fish in hole."
                            ),
                        )
                    )

        # 3. MECHANICAL PACK-OFF vs. DIFFERENTIAL STICKING
        if len(self.torque_history) >= 5:
            avg_torque = sum(self.torque_history) / len(self.torque_history)
            torque_spike = snap.torque_ft_lbf >= 1.6 * avg_torque and snap.torque_ft_lbf >= 8000.0

            if torque_spike:
                # Mechanical Pack-Off signature: BOTH torque spikes AND SPP spikes (annulus restricted)
                if len(self.spp_history) >= 3 and snap.spp_psi > (sum(self.spp_history)/len(self.spp_history) + 200.0):
                    alerts.append(
                        AnomalyAlert(
                            timestamp_s=snap.time_s,
                            anomaly_type=DrillingAnomalyType.MECHANICAL_PACKOFF,
                            severity="CRITICAL",
                            message=(
                                f"MECHANICAL CUTTINGS PACK-OFF: Simultaneous torque spike "
                                f"({snap.torque_ft_lbf:.0f} ft-lbf) and SPP pressure surge (+{snap.spp_psi:.0f} psi). "
                                f"Cuttings bed has bridged around BHA/collars!"
                            ),
                            recommended_action=(
                                "Reduce pump rate immediately to prevent formation breakdown. "
                                "Apply downward jarring; do not pull string into the pack-off pack."
                            ),
                        )
                    )
                # Differential Sticking signature: Torque spikes while SPP is completely normal
                elif snap.pump_spm > 0:
                    alerts.append(
                        AnomalyAlert(
                            timestamp_s=snap.time_s,
                            anomaly_type=DrillingAnomalyType.DIFFERENTIAL_STICKING,
                            severity="WARNING",
                            message=(
                                f"DIFFERENTIAL STICKING RISK: Extreme torque resistance "
                                f"({snap.torque_ft_lbf:.0f} ft-lbf) with normal standpipe pressure. "
                                f"Drill collars embedded in permeable cake under hydrostatic overbalance."
                            ),
                            recommended_action=(
                                "Work pipe dynamically; spot lubricating / pipe-freeing pill; "
                                "reduce mud weight if drilling window permits."
                            ),
                        )
                    )

        self.spp_history.append(snap.spp_psi)
        self.torque_history.append(snap.torque_ft_lbf)

        return alerts
